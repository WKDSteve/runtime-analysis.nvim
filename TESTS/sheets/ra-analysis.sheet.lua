-- Live check: the analysis commands of `:RA` and `:RATelemetry` (task
-- runtime-analysis.nvim/testblatt-bindings-checkliste). Automated: provenance, inspect, loaded
-- snapshot/snapshots, usage start/report/stop, startup start/watch/report/probe/profile and the
-- telemetry basics (status, start/stop, StartAll/StopAll).
-- Not here: the other :RATelemetry reports (they need recorded data), the look of the floats.
return {
  id = "runtime-analysis.analysis",
  title = ":RA provenance, inspect, loaded, usage, startup and the :RATelemetry basics",
  task = "runtime-analysis.nvim/testblatt-bindings-checkliste",
  sizes = { { rows = 40, cols = 120 } },
  steps = {
    { lua = [[dofile(vim.fn.getcwd() .. "/TESTS/sheets/_helpers.lua"); _G.boot()]] },
    { keys = ":RA provenance vim.notify<CR>" },
    {
      expect = [[#_G.notes > 0 and _G.noted("vim.notify")]],
      note = ":RA provenance names the function it looked at",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RA inspect runtime-analysis.parse<CR>" },
    {
      expect = [[#_G.notes > 0 and _G.noted("parse")]],
      note = ":RA inspect walks a loaded module",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RA loaded snapshot runtime-analysis snapone<CR>" },
    { expect = [[_G.noted('loaded snapshot "snapone" saved')]], note = "loaded snapshot saves it" },
    { lua = [[_G.forget()]] },
    { keys = ":RA loaded snapshots runtime-analysis<CR>" },
    {
      expect = [[_G.noted("1 snapshot(s)") and _G.noted("snapone")]],
      note = "loaded snapshots lists it",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RA usage<CR>" },
    { expect = [[_G.noted("usage tracking is not running")]], note = ":RA usage before start" },
    { lua = [[_G.forget()]] },
    { keys = ":RA usage start<CR>" },
    { expect = [[_G.noted("usage tracking started")]], note = ":RA usage start" },
    { keys = ":RA usage start<CR>" },
    { expect = [[_G.noted("already running")]], note = "and a second start is refused" },
    { lua = [[_G.forget()]] },
    { keys = ":RA usage<CR>" },
    { expect = [[#_G.notes > 0 and not _G.noted("not running")]], note = ":RA usage reports" },
    { lua = [[_G.forget()]] },
    { keys = ":RA usage stop<CR>" },
    { expect = [[_G.noted("usage tracking stopped")]], note = ":RA usage stop" },
    { lua = [[_G.forget()]] },
    { keys = ":RA startup probe<CR>" },
    {
      expect = [[_G.noted("measure a startup with:") and vim.fn.getreg('"'):find("--cmd", 1, true) ~= nil]],
      note = ":RA startup probe prints and yanks the --cmd line",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RA startup start<CR>" },
    { expect = [[_G.noted("watching for main-loop stalls")]], note = ":RA startup start" },
    { keys = ":RA startup report<CR>" },
    {
      wait = [[_G.floattext():find("stall", 1, true) ~= nil or _G.noted("stall")]],
      timeout = 8000,
      note = ":RA startup report shows the timeline",
    },
    { keys = "<Esc>" },
    { lua = [[_G.forget()]] },
    { keys = ":RA startup watch<CR>" },
    { expect = [[_G.noted("watching until")]], note = ":RA startup watch" },
    { keys = ":RA startup report<CR>" },
    { keys = "<Esc>" },
    { lua = [[_G.forget()]] },
    { keys = ":RA startup profile 1<CR>" },
    {
      wait = [[_G.noted("median startup over 1 run(s)") or _G.screentext():find("median startup over 1 run(s)", 1, true) ~= nil]],
      timeout = 60000,
      note = ":RA startup profile 1 starts an editor once and reports the cost",
    },
    {
      expect = [[_G.noted("MEDIAN") or _G.screentext():find("MEDIAN", 1, true) ~= nil]],
      note = "with the per-file table",
    },
    { keys = "<Esc>" },
    { lua = [[_G.forget()]] },
    { keys = ":RA startup profile 500<CR>" },
    {
      expect = [[_G.noted("runs must be between 1 and 50")]],
      note = "an absurd run count is refused",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RATelemetry status<CR>" },
    {
      wait = [[_G.noted("NAMESPACE") or _G.screentext():find("NAMESPACE", 1, true) ~= nil or _G.noted("no telemetry")]],
      timeout = 5000,
      note = ":RATelemetry status answers",
    },
    { keys = "<Esc>" },
    { lua = [[_G.forget()]] },
    { keys = ":RATelemetryStartAll<CR>" },
    {
      expect = [[_G.noted("started ") and _G.noted("instance(s)")]],
      note = ":RATelemetryStartAll reports how many instances it started",
    },
    { lua = [[_G.forget()]] },
    { keys = ":RATelemetryStopAll<CR>" },
    {
      expect = [[_G.noted("stopped ") and _G.noted("instance(s)")]],
      note = ":RATelemetryStopAll reports how many it stopped",
    },
  },
  judge = { "the startup profile and stall floats read well" },
  manual = {
    "`:RATelemetry` reports, export, flamegraph, cost, snapshot and compare on recorded data",
    "`:RATelemetrySetupAll`, `ResetAll`, `NvimConfig` and `NvimConfigFull` against a real configuration",
    "the Session marks keys (`<C-e>`, `<M-1>`..`<M-9>`, `<M-S>`) and the slot bar belong to the session plugin, not to this one",
  },
